"""The evaluation's presenter: one source for everything a reader sees (``python -m evals.present``).

Analysis code writes results JSON (``evals.run``, ``evals.analysis``, ``evals.ask``, the replays of ``scripts/``);
the presenter only formats it. :mod:`evals.present.model` reads ``evals/results/*.json`` and writes
``evals/present/presentation.json``: every number a reader sees, with the role of each results file. The renderers
read that file alone and use the standard library only, so the report page builds anywhere:

* the README's evaluation block, between :data:`BEGIN` and :data:`END` (the rest of the README is left as it is);
* ``docs/evals.md``, the evaluation report, and ``docs/evals-history.md``, the lab notebook of every earlier run;
* the charts, ``docs/assets/eval-*-{light,dark}.svg``, hand-written SVG with a title, a description naming every
  value and a table twin;
* the report page (``--site DIR``): one static HTML file, no script, with a CSV for every chart, published next to
  the online demo at :data:`PAGES_URL` by ``.github/workflows/demo.yml``.

``python -m evals.present --write`` writes the committed outputs; ``--check`` renders them again and fails on any
byte that differs (CI). The headline is chosen by rule: the pre-registered final run once it exists, else the
held-out splits as recorded once, re-analysed (``evals.analysis``) and labelled not pre-registered. Re-scored,
iterated or replayed numbers never feed it.

No output holds a letter's text: ids, counts, classes and metric values only.
"""

