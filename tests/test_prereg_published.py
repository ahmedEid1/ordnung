"""How the pre-registration is checked after publication (``scripts/prereg_published.py``), on throwaway repositories.

Once ``evals/preregistration/published-0.4.0.json`` names the commit that published the final run,
``tests/test_preregistration.py`` checks the freeze at that commit (its own copy of the test, in a temporary worktree)
and keeps at HEAD only what holds for good. These cases build a small repository in ``tmp_path`` (a freeze, a
registration, a publish commit and a later commit) so that they run anywhere, without the real publish commit.
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
from pathlib import Path
from typing import Any

import pytest
from scripts import prereg_published

ISSUE = "https://github.com/example/repo/issues/54"
AMENDMENT = f"{ISSUE}#issuecomment-123456789"
PREREG = "evals/preregistration/final-0.4.0.json"
DEVIATIONS = "evals/preregistration/deviations-0.4.0.json"
FINAL_PATTERN = "evals/results/*-claude-sonnet-5-final.json"
FINAL = "evals/results/2026-11-27-claude-sonnet-5-final.json"
READ = "evals/results/2026-11-24-claude-sonnet-5-holdout4-r1.json"
TEMPLATE = "Deviations from the pre-registration, recorded at the time and listed in `{deviations_file}`: {deviations}."
BEGIN = "<!-- evals:begin: generated by `python -m evals.present`; do not edit -->"
END = "<!-- evals:end -->"


def _git(root: Path, *args: str) -> str:
    done = subprocess.run(
        [
            "git",
            "-C",
            str(root),
            "-c",
            "user.name=t",
            "-c",
            "user.email=t@example.invalid",
            "-c",
            "commit.gpgsign=false",
            *args,
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    return done.stdout.strip()


def _put(root: Path, path: str, text: str) -> None:
    target = root / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")


def _commit(root: Path, message: str) -> str:
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", message)
    return _git(root, "rev-parse", "HEAD")


def _readme(count: int, *, wrap: int = 60) -> str:
    sentence = TEMPLATE.format(deviations_file=DEVIATIONS, deviations=count)
    paragraph = f"**Final run, pre-registered.** Ordnung dates 80.0 % right. {sentence} Ordnung is ahead."
    lines, line = [], ""
    for word in paragraph.split():
        if line and len(line) + 1 + len(word) > wrap:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    lines.append(line)
    block = [BEGIN, *lines, "", "**Where it falls short:** 3 wrong dates.<br>", END]
    return "\n".join(["# Ordnung", "", "Intro.", "", *block, "", "Why these numbers can be checked.", ""])


def _deviation(ident: str, kind: str) -> dict[str, Any]:
    return {"id": ident, "kind": kind, "what": f"{ident} happened"}


class World:
    """A freeze, a registration, a publish commit and a later commit that adds the record."""

    def __init__(self, root: Path) -> None:
        self.root = root
        root.mkdir()
        _git(root, "init", "-q")
        _put(root, "README.md", "# Ordnung\n\nIntro.\n")
        _put(root, "src/ordnung/__init__.py", '__version__ = "0.4.0"\n')
        _put(root, "evals/results/INDEX.json", "{}\n")
        self.freeze = _commit(root, "the freeze")
        prereg = '{"id": "final-0.4.0"}\n'
        self.prereg_sha = hashlib.sha256(prereg.encode()).hexdigest()
        _put(root, PREREG, prereg)
        _put(root, "evals/preregistration/final-0.4.0.md", "# The pre-registration\n")
        _put(root, "evals/preregistration/power-0.4.0.json", '{"power": 1}\n')
        _put(root, "evals/preregistration/calibration-0.4.0.json", '{"calibration": 1}\n')
        _put(root, DEVIATIONS, "[]\n")
        self.registration = _commit(root, "the pre-registration")
        _put(root, "evals/preregistration/phase2-0.4.0.json", '{"files": {}}\n')
        _put(root, "evals/results/pending/2026-11-24-claude-sonnet-5-holdout4-r1.json", '{"meta": {}}\n')
        _put(root, DEVIATIONS, json.dumps([_deviation("D001", "retake")]) + "\n")
        self.checkpoint = _commit(root, f"Final run checkpoint: phase2\n\n{ISSUE}")
        (root / "evals/results/pending/2026-11-24-claude-sonnet-5-holdout4-r1.json").unlink()
        _put(root, READ, '{"meta": {"split": "holdout4", "backend": "live"}}\n')
        analysis = {"meta": {"kind": "final", "prereg": {"file": PREREG, "sha256": self.prereg_sha}}}
        _put(root, FINAL, json.dumps(analysis) + "\n")
        _put(root, "evals/results/INDEX.json", '{"rows": 2}\n')
        _put(root, "README.md", _readme(1))
        self.publish = _commit(root, "Final evaluation of 0.4.0: results, analyses and report")
        _put(root, "src/ordnung/engine.py", "# a change after publication\n")
        self.after = _commit(root, "a product change after publication")

    def record(self, **changes: Any) -> dict[str, Any]:
        record: dict[str, Any] = {
            "schema": prereg_published.SCHEMA,
            "commit": self.publish,
            "amendment": AMENDMENT,
            "checked_by": {path: "0" * 64 for path in prereg_published.CHECKED_BY},
        }
        record.update(changes)
        return {key: value for key, value in record.items() if value is not None}

    def problems(self, record: dict[str, Any]) -> list[str]:
        return prereg_published.record_problems(record, self.root, freeze=self.freeze, issue=ISSUE)

    def finals(self, commit: str) -> list[str]:
        return prereg_published.final_analyses_at(
            self.root, commit, FINAL_PATTERN, {"file": PREREG, "sha256": self.prereg_sha}
        )


@pytest.fixture()
def world(tmp_path: Path) -> World:
    return World(tmp_path / "repo")


