def test_a_record_naming_the_publish_commit_holds(world: World) -> None:
    assert world.problems(world.record()) == []
    assert world.finals(world.publish) == [FINAL]
    with_about = world.record(about="The commit that published the final run.")
    assert world.problems(with_about) == []


def test_a_commit_before_publication_publishes_no_final_analysis(world: World) -> None:
    """The record is a commit of HEAD's history, but only one that published a final analysis of the registered
    pre-registration can end the freeze."""
    assert world.problems(world.record(commit=world.checkpoint)) == []
    assert world.finals(world.checkpoint) == []
    assert world.finals(world.registration) == []
    assert world.finals(world.publish) == [FINAL]
    # an analysis of another pre-registration does not count
    assert (
        prereg_published.final_analyses_at(
            world.root, world.publish, FINAL_PATTERN, {"file": PREREG, "sha256": "0" * 64}
        )
        == []
    )


def test_a_commit_outside_head_s_history_or_unknown_fails(world: World) -> None:
    _git(world.root, "checkout", "-q", "-b", "side", world.publish)
    _put(world.root, "side.txt", "a commit main never had\n")
    side = _commit(world.root, "a side commit")
    _git(world.root, "checkout", "-q", "-")
    assert any("not in HEAD's history" in p for p in world.problems(world.record(commit=side)))
    unknown = "1234567" * 5 + "12345"
    assert any("not a commit" in p for p in world.problems(world.record(commit=unknown)))


def test_the_record_is_strict(world: World) -> None:
    assert any("schema" in p for p in world.problems(world.record(schema="ordnung-prereg-published/0")))
    assert any("commit" in p for p in world.problems(world.record(commit=world.publish[:12])))
    assert any("unknown key" in p for p in world.problems(world.record(sha=world.publish)))
    assert any("missing" in p for p in world.problems(world.record(amendment=None)))
    assert prereg_published.record_problems([], world.root, freeze=world.freeze, issue=ISSUE) != []


