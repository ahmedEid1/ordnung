def _readme_problems(now: str, published: str, deviations: int) -> list[str]:
    return prereg_published.readme_problems(
        now, published, template=TEMPLATE, deviations_file=DEVIATIONS, deviations=deviations
    )


def test_the_readme_keeps_the_published_block() -> None:
    published = _readme(2)
    assert _readme_problems(published, published, 2) == []
    # the text around the block may change
    assert _readme_problems(published.replace("Intro.", "Another intro."), published, 2) == []
    # the block may be laid out again, word for word the same
    assert _readme_problems(_readme(2, wrap=40), published, 2) == []
    edited = published.replace("80.0 %", "81.0 %")
    assert any("differs from" in p for p in _readme_problems(edited, published, 2))
    shorter = published.replace("**Where it falls short:** 3 wrong dates.<br>\n", "")
    assert any("differs from" in p for p in _readme_problems(shorter, published, 2))
    gone = published.replace(BEGIN, "").replace(END, "")
    assert any("no generated block" in p for p in _readme_problems(gone, published, 2))


def test_only_the_count_of_deviations_may_grow_with_the_deviations_file() -> None:
    """A label error or a scorer bug found after publication is a deviation appended to the file, and the block's
    head sentence counts the file's entries (``head.deviations``): that number may grow with the file, nothing else."""
    published = _readme(2)
    assert _readme_problems(_readme(3), published, 3) == []
    assert _readme_problems(_readme(12, wrap=40), published, 12) == []
    assert any("deviations file holds 3" in p for p in _readme_problems(_readme(2), published, 3))
    assert any("fewer" in p for p in _readme_problems(_readme(1), published, 1))
    twice = _readme(3).replace("Ordnung is ahead.", TEMPLATE.format(deviations_file=DEVIATIONS, deviations=3))
    assert _readme_problems(twice, published, 3) != []


