def test_files_stay_byte_for_byte_what_the_publish_commit_holds(world: World) -> None:
    paths = [PREREG, "evals/preregistration/final-0.4.0.md", "evals/preregistration/phase2-0.4.0.json"]
    assert prereg_published.unchanged_problems(world.root, world.publish, paths) == []
    (world.root / PREREG).write_text('{"id": "final-0.4.0", "edited": true}\n', encoding="utf-8")
    (world.root / "evals/preregistration/final-0.4.0.md").unlink()
    found = prereg_published.unchanged_problems(world.root, world.publish, paths)
    assert [p.split(":", 1)[0] for p in found] == [PREREG, "evals/preregistration/final-0.4.0.md"]
    assert "changed since" in found[0] and "removed since" in found[1]
    assert prereg_published.unchanged_problems(world.root, world.registration, ["evals/results/x.json"]) == [
        "evals/results/x.json: not at the publish commit"
    ]


def test_the_results_files_the_final_run_added_stay_and_new_ones_may_join(world: World) -> None:
    """The files the history from the freeze to the publish commit added under evals/results (the checkpoints of
    ``pending/`` aside) and evals/retakes: a re-score after publication is a new ``-rescored`` file beside them."""
    added = prereg_published.added_results(world.root, world.freeze, world.publish)
    assert added == [READ, FINAL]  # INDEX.json was changed, not added; pending/ is left out
    assert prereg_published.unchanged_problems(world.root, world.publish, added) == []
    _put(world.root, "evals/results/2026-12-10-claude-sonnet-5-holdout4-r1-rescored.json", "{}\n")
    _put(world.root, "evals/results/INDEX.json", '{"rows": 3}\n')
    assert prereg_published.unchanged_problems(world.root, world.publish, added) == []
    _put(world.root, READ, '{"meta": {"split": "holdout4", "backend": "live", "rescored": true}}\n')
    assert [
        p.split(":", 1)[0] for p in prereg_published.unchanged_problems(world.root, world.publish, added)
    ] == [READ]


def test_deviations_are_only_appended_after_publication_and_only_label_or_scorer_errors(world: World) -> None:
    published = [_deviation("D001", "retake"), _deviation("D002", "code_hash_changed")]
    later = [*published, _deviation("D003", "label_error"), _deviation("D004", "scorer_bug")]
    assert prereg_published.deviations_kept_problems(published, published) == []
    assert prereg_published.deviations_kept_problems(later, published) == []
    rewritten = [dict(published[0], what="said again"), published[1]]
    assert any("append-only" in p for p in prereg_published.deviations_kept_problems(rewritten, published))
    assert any(
        "append-only" in p for p in prereg_published.deviations_kept_problems(published[1:], published)
    )
    assert any(
        "append-only" in p for p in prereg_published.deviations_kept_problems(published[::-1], published)
    )
    late_retake = [*published, _deviation("D003", "retake")]
    assert prereg_published.deviations_kept_problems(late_retake, published) == [
        "D003: a retake deviation recorded after publication (only label_error and scorer_bug can be)"
    ]
    assert prereg_published.deviations_kept_problems({"D001": 1}, published) != []


