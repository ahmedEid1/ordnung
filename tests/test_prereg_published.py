PASSING = """
import evals
import ordnung
from scripts import marker


def test_the_package_is_the_published_one():
    assert ordnung.MARK == "published"


def test_the_checks_are_the_published_ones():
    assert evals.MARK == marker.MARK == "published"
"""


def _inner_repo(tmp_path: Path, test_file: str) -> tuple[Path, str]:
    root = tmp_path / "inner"
    root.mkdir()
    _git(root, "init", "-q")
    _put(root, "pyproject.toml", '[tool.pytest.ini_options]\npythonpath = ["."]\naddopts = "-q"\n')
    _put(root, "src/ordnung/__init__.py", 'MARK = "published"\n')
    _put(root, "evals/__init__.py", 'MARK = "published"\n')
    _put(root, "scripts/marker.py", 'MARK = "published"\n')
    _put(root, "tests/test_preregistration.py", test_file)
    published = _commit(root, "the publish commit")
    for path in ("src/ordnung/__init__.py", "evals/__init__.py", "scripts/marker.py"):
        _put(root, path, 'MARK = "head"\n')
    _put(root, "tests/test_preregistration.py", "def test_head():\n    raise AssertionError('HEAD ran')\n")
    _commit(root, "after publication")
    return root, published


def _worktrees(root: Path) -> list[str]:
    return [
        line
        for line in _git(root, "worktree", "list", "--porcelain").splitlines()
        if line.startswith("worktree")
    ]


def test_the_publish_commit_s_test_runs_on_its_own_code_and_the_worktree_goes(tmp_path: Path) -> None:
    root, published = _inner_repo(tmp_path, PASSING)
    before = _worktrees(root)
    outcome = prereg_published.run_frozen_tests(root, published, tmp_path / "scratch", timeout=300)
    assert prereg_published.outcome_problems(outcome) == [], outcome.output
    assert sorted(name for name, _ in outcome.tests) == [
        "test_the_checks_are_the_published_ones",
        "test_the_package_is_the_published_one",
    ]
    assert {result for _, result in outcome.tests} == {"passed"}
    # every first-party module the run imported came from the worktree, never from this checkout or its install
    assert {"ordnung", "evals", "scripts", "scripts.marker"} <= set(outcome.modules)
    for name, files in outcome.modules.items():
        assert files and all(Path(f).is_relative_to(outcome.tree) for f in files), (name, files)
    assert _worktrees(root) == before
    assert not outcome.tree.exists()


