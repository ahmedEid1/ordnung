def test_a_run_that_does_not_end_is_stopped_and_its_worktree_removed(tmp_path: Path) -> None:
    root, published = _inner_repo(tmp_path, "import time\n\n\ndef test_hangs():\n    time.sleep(120)\n")
    before = _worktrees(root)
    with pytest.raises(subprocess.TimeoutExpired):
        prereg_published.run_frozen_tests(root, published, tmp_path / "scratch", timeout=3)
    assert _worktrees(root) == before
    assert not (tmp_path / "scratch" / "published").exists()


def test_the_inner_run_s_environment_puts_the_worktree_first(tmp_path: Path) -> None:
    """The worktree's ``src`` and root lead ``PYTHONPATH`` (joined with ``os.pathsep``), and nothing of the outer run's
    Python or pytest settings (``PYTHONPATH``, ``PYTEST_ADDOPTS``, coverage's subprocess hooks) reaches it."""
    tree = tmp_path / "tree"
    outer = {
        "PATH": os.environ.get("PATH", ""),
        "PYTHONPATH": "/somewhere/else",
        "PYTEST_ADDOPTS": "-x",
        "PYTEST_XDIST_WORKER": "gw0",
        "COV_CORE_SOURCE": "ordnung",
        "COVERAGE_PROCESS_START": "pyproject.toml",
        "ORDNUNG_OCR": "off",
    }
    env = prereg_published.inner_environment(tree, tmp_path / "probe", outer)
    assert env["PYTHONPATH"].split(os.pathsep) == [str(tree / "src"), str(tree), str(tmp_path / "probe")]
    assert not {"PYTEST_ADDOPTS", "PYTEST_XDIST_WORKER", "COV_CORE_SOURCE", "COVERAGE_PROCESS_START"} & set(
        env
    )
    assert env["ORDNUNG_OCR"] == "off" and env["PATH"] == outer["PATH"]


