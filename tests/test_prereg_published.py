PASSING = """
import evals
import ordnung
from scripts import marker


def test_the_package_is_the_published_one():
    assert ordnung.MARK == "published"


def test_the_checks_are_the_published_ones():
    assert evals.MARK == marker.MARK == "published"
"""


def _inner_repo(tmp_path: Path, test_file: str) -> tuple[Path, str]:
    root = tmp_path / "inner"
    root.mkdir()
    _git(root, "init", "-q")
    _put(root, "pyproject.toml", '[tool.pytest.ini_options]\npythonpath = ["."]\naddopts = "-q"\n')
    _put(root, "src/ordnung/__init__.py", 'MARK = "published"\n')
    _put(root, "evals/__init__.py", 'MARK = "published"\n')
    _put(root, "scripts/marker.py", 'MARK = "published"\n')
    _put(root, "tests/test_preregistration.py", test_file)
    published = _commit(root, "the publish commit")
    for path in ("src/ordnung/__init__.py", "evals/__init__.py", "scripts/marker.py"):
        _put(root, path, 'MARK = "head"\n')
    _put(root, "tests/test_preregistration.py", "def test_head():\n    raise AssertionError('HEAD ran')\n")
    _commit(root, "after publication")
    return root, published


def _worktrees(root: Path) -> list[str]:
    return [
        line
        for line in _git(root, "worktree", "list", "--porcelain").splitlines()
        if line.startswith("worktree")
    ]


def test_the_publish_commit_s_test_runs_on_its_own_code_and_the_worktree_goes(tmp_path: Path) -> None:
    root, published = _inner_repo(tmp_path, PASSING)
    before = _worktrees(root)
    outcome = prereg_published.run_frozen_tests(root, published, tmp_path / "scratch", timeout=300)
    assert prereg_published.outcome_problems(outcome) == [], outcome.output
    assert sorted(name for name, _ in outcome.tests) == [
        "test_the_checks_are_the_published_ones",
        "test_the_package_is_the_published_one",
    ]
    assert {result for _, result in outcome.tests} == {"passed"}
    # every first-party module the run imported came from the worktree, never from this checkout or its install
    assert {"ordnung", "evals", "scripts", "scripts.marker"} <= set(outcome.modules)
    for name, files in outcome.modules.items():
        assert files and all(Path(f).is_relative_to(outcome.tree) for f in files), (name, files)
    assert _worktrees(root) == before
    assert not outcome.tree.exists()


def test_a_skip_a_failure_or_a_test_not_run_is_reported(tmp_path: Path) -> None:
    file = (
        PASSING
        + """

import pytest


def test_skipped():
    pytest.skip("not yet")


def test_failing():
    assert ordnung.MARK == "head"


@pytest.mark.slow
def test_left_out():
    pass


def test_errors_in_setup(missing_fixture):
    pass
"""
    )
    root, published = _inner_repo(tmp_path, file)
    outcome = prereg_published.run_frozen_tests(
        root, published, tmp_path / "scratch", timeout=300, extra_args=("-m", "not slow")
    )
    found = prereg_published.outcome_problems(outcome)
    assert any(p.startswith("pytest exited") for p in found), found
    assert "test_skipped: skipped (every check must run at the publish commit)" in found
    assert "test_failing: failed" in found
    assert "test_errors_in_setup: error" in found
    assert "test_left_out: not run" in found
    assert not outcome.tree.exists()


def test_a_run_that_does_not_end_is_stopped_and_its_worktree_removed(tmp_path: Path) -> None:
    root, published = _inner_repo(tmp_path, "import time\n\n\ndef test_hangs():\n    time.sleep(120)\n")
    before = _worktrees(root)
    with pytest.raises(subprocess.TimeoutExpired):
        prereg_published.run_frozen_tests(root, published, tmp_path / "scratch", timeout=3)
    assert _worktrees(root) == before
    assert not (tmp_path / "scratch" / "published").exists()


def test_the_inner_run_s_environment_puts_the_worktree_first(tmp_path: Path) -> None:
    """The worktree's ``src`` and root lead ``PYTHONPATH`` (joined with ``os.pathsep``), and nothing of the outer run's
    Python or pytest settings (``PYTHONPATH``, ``PYTEST_ADDOPTS``, coverage's subprocess hooks) reaches it."""
    tree = tmp_path / "tree"
    outer = {
        "PATH": os.environ.get("PATH", ""),
        "PYTHONPATH": "/somewhere/else",
        "PYTEST_ADDOPTS": "-x",
        "PYTEST_XDIST_WORKER": "gw0",
        "COV_CORE_SOURCE": "ordnung",
        "COVERAGE_PROCESS_START": "pyproject.toml",
        "ORDNUNG_OCR": "off",
    }
    env = prereg_published.inner_environment(tree, tmp_path / "probe", outer)
    assert env["PYTHONPATH"].split(os.pathsep) == [str(tree / "src"), str(tree), str(tmp_path / "probe")]
    assert not {"PYTEST_ADDOPTS", "PYTEST_XDIST_WORKER", "COV_CORE_SOURCE", "COVERAGE_PROCESS_START"} & set(
        env
    )
    assert env["ORDNUNG_OCR"] == "off" and env["PATH"] == outer["PATH"]


